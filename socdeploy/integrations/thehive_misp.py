"""Interconnexion TheHive (SIRP) <-> MISP (CTI).

Permet à TheHive d'interroger directement MISP pour enrichir les observables d'un incident
avec les indicateurs de compromission (IoCs) connus de la communauté.
"""

from pathlib import Path
from typing import Dict, Any
from loguru import logger


def setup_thehive_misp_integration(
    deploy_dir: Path,
    misp_url: str = "https://localhost:8443",
    misp_api_key: str = "AUTOGENERATED_MISP_KEY"
) -> Dict[str, Any]:
    """Configure la liaison entre TheHive et l'instance MISP."""
    app_conf = deploy_dir / "thehive" / "config" / "application.conf"
    result = {
        "status": "configured",
        "misp_url": misp_url,
        "description": "Enrichissement automatique des observables d'incidents TheHive via les flux IoCs de MISP"
    }

    if app_conf.exists():
        try:
            content = app_conf.read_text(encoding="utf-8")
            if "misp {" not in content:
                misp_block = (
                    "\n# Interconnexion TheHive <-> MISP (SOC Deploy Framework)\n"
                    "misp {\n"
                    f'  url = "{misp_url}"\n'
                    f'  key = "{misp_api_key}"\n'
                    "  caseTags = [\"misp-sync\"]\n"
                    "}\n"
                )
                app_conf.write_text(content + misp_block, encoding="utf-8")
                logger.info(f"Configuration MISP ajoutée dans {app_conf}.")
            result["status"] = "active"
        except Exception as e:
            result["status"] = "partial"
            result["error"] = str(e)

    return result
