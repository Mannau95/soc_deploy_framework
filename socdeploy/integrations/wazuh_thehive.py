"""Interconnexion Wazuh (SIEM) -> TheHive (SIRP).

Permet à Wazuh de créer automatiquement un dossier d'incident dans TheHive
dès qu'une alerte critique (ex: niveau >= 10) est détectée par le SIEM.
"""

import os
import shutil
from pathlib import Path
from typing import Dict, Any, Tuple
from loguru import logger
from socdeploy.utils import run_command


def inject_thehive_integration(ossec_conf_text: str, thehive_url: str = "http://localhost:9000", min_level: int = 10) -> Tuple[str, bool]:
    """Injecte le bloc <integration> pour TheHive dans ossec.conf si absent."""
    if "custom-wazuh2thehive" in ossec_conf_text or f"<hook_url>{thehive_url}</hook_url>" in ossec_conf_text:
        return ossec_conf_text, False

    block = (
        "\n  <!-- Interconnexion Wazuh SIEM -> TheHive SIRP (SOC Deploy Framework) -->\n"
        "  <integration>\n"
        "    <name>custom-wazuh2thehive</name>\n"
        f"    <hook_url>{thehive_url}</hook_url>\n"
        "    <api_key>AUTOGENERATED_THEHIVE_KEY</api_key>\n"
        "    <alert_format>json</alert_format>\n"
        f"    <level>{min_level}</level>\n"
        "  </integration>\n"
    )

    if "</ossec_config>" in ossec_conf_text:
        idx = ossec_conf_text.rfind("</ossec_config>")
        return ossec_conf_text[:idx] + block + ossec_conf_text[idx:], True
    else:
        return ossec_conf_text + f"\n<ossec_config>{block}</ossec_config>\n", True


def setup_wazuh_thehive_integration(
    deploy_dir: Path,
    wazuh_method: str = "native",
    thehive_port: int = 9000,
    min_level: int = 10
) -> Dict[str, Any]:
    """Configure la transmission automatique des alertes critiques Wazuh vers TheHive."""
    thehive_url = f"http://localhost:{thehive_port}"
    result = {
        "status": "configured",
        "thehive_url": thehive_url,
        "trigger_level": min_level,
        "description": f"Création automatique d'alertes/cas dans TheHive pour les alertes Wazuh de niveau >= {min_level}"
    }

    if wazuh_method == "native":
        ossec_conf = Path("/var/ossec/etc/ossec.conf")
        if ossec_conf.exists():
            try:
                content = ossec_conf.read_text(encoding="utf-8")
                new_content, modified = inject_thehive_integration(content, thehive_url, min_level)
                if modified:
                    shutil.copy(ossec_conf, ossec_conf.with_suffix(".conf.bak"))
                    ossec_conf.write_text(new_content, encoding="utf-8")
                    if os.name != "nt":
                        run_command(["systemctl", "restart", "wazuh-manager"], check=False)
                    logger.info("Configuration Wazuh -> TheHive activée dans /var/ossec/etc/ossec.conf.")
                result["status"] = "active"
            except Exception as e:
                result["status"] = "partial"
                result["error"] = str(e)
    elif wazuh_method == "docker":
        wazuh_conf = deploy_dir / "wazuh" / "config" / "wazuh_cluster" / "wazuh_manager.conf"
        if wazuh_conf.exists():
            content = wazuh_conf.read_text(encoding="utf-8")
            thehive_docker_url = f"http://thehive:9000"
            new_content, modified = inject_thehive_integration(content, thehive_docker_url, min_level)
            if modified:
                wazuh_conf.write_text(new_content, encoding="utf-8")
            result["status"] = "active"

    return result
